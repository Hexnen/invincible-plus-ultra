const lang = () => { try { return String(globalThis.game?.i18n?.lang ?? "en"); } catch { return "en"; } };
function plural(l, n, forms) {
  const a = Math.abs(Number(n) || 0);
  if (l !== "pl") return a === 1 ? forms[0] : forms[1] ?? forms[0];
  if (a === 1) return forms[0];
  return a % 10 >= 2 && a % 10 <= 4 && !(a % 100 >= 12 && a % 100 <= 14) ? forms[1] : forms[2] ?? forms[1];
}
export function tIn(l, key, params = {}) {
  const pl = String(l).startsWith("pl"), s = (pl ? PL[key] : null) ?? EN[key];
  if (typeof s !== "string") return key;
  return s.replace(/\{(\w+)\|([^{}]*)\}/g, (m, k, forms) => plural(pl ? "pl" : "en", params?.[k], forms.split("|")))
    .replace(/\{(\w+)\}/g, (m, k) => (params?.[k] !== undefined && params?.[k] !== null ? String(params[k]) : m));
}
export const t = (key, params = {}) => tIn(lang(), key, params);
