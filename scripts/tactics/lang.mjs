const fill = (s, data) => String(s).replace(/\{(\w+)\}/g, (_m, k) => (data?.[k] ?? `{${k}}`));
const lang = () => { try { return globalThis.game?.i18n?.lang ?? "en"; } catch { return "en"; } };
/** t("ITAC.err.stale") or t("ITAC.Prompt.veteran.Body", { name, card }). Falls back to English, then to the key. */
export function t(key, data) {
  const table = lang().startsWith("pl") ? PL : EN;
  return fill(table[key] ?? EN[key] ?? key, data);
}
/** Text of an error object { key, code, params }. */
export const errText = (e) => (e ? t(EN[e.key] ? e.key : `ITAC.err.${EN[`ITAC.err.${e.code}`] ? e.code : "internal"}`, { msg: e.code ?? "", ...(e.params ?? {}) }) : "");
