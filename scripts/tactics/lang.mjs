/** The form of a counted word (U26). English: [one, other]. Polish: [one, few, many]: 1 kość, 2-4 kości, 5+ kości, with 12-14 and
    every number ending in 0, 1, 5-9 taking the last form (1 strefę, 3 strefy, 5 stref, 12 stref, 22 strefy). Not a whole number: the last form. */
export function plural(lang, n, forms) {
  const v = typeof n === "number" ? n : typeof n === "string" && n.trim() !== "" ? Number(n) : NaN, last = forms[forms.length - 1];
  if (!Number.isInteger(v)) return last;
  const a = Math.abs(v);
  if (a === 1) return forms[0];
  if (lang !== "pl" || forms.length < 3) return last;
  return a % 10 >= 2 && a % 10 <= 4 && !(a % 100 >= 12 && a % 100 <= 14) ? forms[1] : last;
}
/** t(key, params, fallback): the string in the client's language, {placeholders} filled (one without a value stays as written);
    falls back to English, then to `fallback` (default: the key). A counted word is written `{n|one|few|many}` (Polish) or
    `{n|one|other}` (English) beside its `{n}` and takes the form the number asks for. */
export function t(key, params = {}, fallback = key) {
  const own = table(), s = own[key] ?? EN[key];
  if (typeof s !== "string") return fallback;
  const lang = own === PL && key in PL ? "pl" : "en";
  return s.replace(/\{(\w+)\|([^{}]*)\}/g, (m, k, forms) => plural(lang, params?.[k], forms.split("|")))
    .replace(/\{(\w+)\}/g, (m, k) => (params?.[k] !== undefined && params?.[k] !== null ? String(params[k]) : m));
}
/** Text of an error object { key, code, params }. An unknown code reads as the internal error; the reason of `illegal` (and of
    `noAction`, `busy`) is itself a key (ITAC.reason.<reason>), shown as written when there is no such key. */
export function errText(e) {
  if (!e) return "";
  const known = typeof e.key === "string" && e.key in EN ? e.key : `ITAC.err.${`ITAC.err.${e.code}` in EN ? e.code : "internal"}`;
  const p = e.params ?? {};
  const reason = p.reason ? t(`ITAC.reason.${p.reason}`, p, String(p.reason)) : t("ITAC.reason.rules");
  return t(known, { msg: e.code ?? "", ...p, reason });
}
