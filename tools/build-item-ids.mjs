/* node tools/build-item-ids.mjs [--check] -- writes scripts/i18n/item-ids.mjs: which compendium identifier carries which English item name.
   Reads the LevelDB packs of the installed system and of invincible-core (COPIES of them: a running Foundry holds the LOCK of the
   originals) with the classic-level of the Foundry install. Nothing but identifiers, types and names leaves the packs.
   Paths: FOUNDRY_DATA (default %LOCALAPPDATA%/FoundryVTT/Data), FOUNDRY_APP (default C:/Program Files/Foundry Virtual Tabletop/resources/app).
   --check: exit 1 when the file on disk differs from what the packs say now (scripts/i18n/check-names.mjs calls `scan()` for the same). */
import { createRequire } from "node:module";
import { cpSync, statSync, mkdtempSync, rmSync, existsSync, readFileSync, writeFileSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { NAMES_PL } from "../scripts/i18n/item-names-pl.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = join(ROOT, "scripts", "i18n", "item-ids.mjs");
const DATA = process.env.FOUNDRY_DATA ?? join(process.env.LOCALAPPDATA ?? "", "FoundryVTT", "Data");
const APP = process.env.FOUNDRY_APP ?? "C:/Program Files/Foundry Virtual Tabletop/resources/app";
export const TYPES = ["power", "boost", "limit", "talent", "drawback", "gear", "vehicleWeapon", "powerSource", "criticalInjury"];
const ITEM_PACKS = [["modules/invincible-core/packs", ["powers", "boosts", "limits", "talents", "drawbacks", "gears", "power-sources"]], ["systems/invincible/packs", ["critical-injuries"]]];
const ACTOR_PACKS = [["modules/invincible-core/packs", ["heroes-villans", "npcs-creatures"]]];
const bare = (s) => String(s).replace(/\s*(\([^)]*\)|[x×]\s*\d+)\s*$/i, "").trim();

async function read(dir) {
  const { ClassicLevel } = createRequire(import.meta.url)(join(APP, "node_modules", "classic-level"));
  const tmp = mkdtempSync(join(tmpdir(), "ipu-pack-"));
  try {
    for (const f of readdirSync(dir)) if (f !== "LOCK" && statSync(join(dir, f)).isFile()) cpSync(join(dir, f), join(tmp, f));
    const db = new ClassicLevel(tmp, { valueEncoding: "json" }); await db.open();
    const out = []; for await (const [k, v] of db.iterator()) out.push([k, v]); await db.close();
    return out;
  } finally { rmSync(tmp, { recursive: true, force: true }); }
}
/** -> { packs: { type: { name: [ids] } }, embedded: { type: { name: [ids] } } } or null when the packs or classic-level are not there */
export async function scan() {
  if (!existsSync(join(APP, "node_modules", "classic-level"))) return null;
  const packs = {}, embedded = {}, put = (o, t, n, id) => { ((o[t] ??= {})[n] ??= []).push(id); };
  for (const [base, names] of ITEM_PACKS) for (const p of names) {
    const dir = join(DATA, base, p); if (!existsSync(dir)) return null;
    for (const [k, v] of await read(dir)) if (k.startsWith("!items!") && TYPES.includes(v.type)) put(packs, v.type, v.name, v._id);
  }
  for (const [base, names] of ACTOR_PACKS) for (const p of names) {
    const dir = join(DATA, base, p); if (!existsSync(dir)) return null;
    for (const [k, v] of await read(dir)) {
      if (!k.startsWith("!actors.items!") || !TYPES.includes(v.type) || v._stats?.compendiumSource) continue;      // an embedded item that names its source is found through it
      const known = (n) => packs[v.type]?.[n] || NAMES_PL[v.type]?.[n];
      put(embedded, v.type, known(v.name) ? v.name : known(bare(v.name)) ? bare(v.name) : v.name, v._id);
    }
  }
  return { packs, embedded };
}
const sorted = (o) => Object.fromEntries(Object.keys(o).sort().map((t) => [t, Object.fromEntries(Object.keys(o[t]).sort().map((n) => [n, o[t][n].slice().sort().join("")]))]));
export function render(s) {
  const body = (o) => JSON.stringify(sorted(o), null, 1).replace(/\n {2}/g, " ").replace(/\n }/g, " }");
  return `/* GENERATED by tools/build-item-ids.mjs from the installed compendia. Do not edit: run the tool again after an update of the system or of
   invincible-core (scripts/i18n/check-names.mjs fails when this file is behind the packs).
   type -> English name as the compendium has it -> the identifiers that carry it, 16 characters each, glued together.
   PACK_IDS: the entries of the item compendia. EMBEDDED_IDS: items on the pregenerated characters of the compendia that do not name a
   source of their own (found by the identifier they keep when the character is imported). */
export const PACK_IDS = ${body(s.packs)};
export const EMBEDDED_IDS = ${body(s.embedded)};
`;
}
if (/build-item-ids.mjs$/.test(process.argv[1] ?? "")) {
  const s = await scan();
  if (!s) { console.log("packs or classic-level not found: nothing written"); process.exit(2); }
  const text = render(s);
  if (process.argv.includes("--check")) { const same = existsSync(OUT) && readFileSync(OUT, "utf8") === text; console.log(same ? "item-ids.mjs is current" : "item-ids.mjs is behind the packs"); process.exit(same ? 0 : 1); }
  writeFileSync(OUT, text);
  const n = (o) => Object.values(o).reduce((a, t) => a + Object.values(t).reduce((b, ids) => b + ids.length, 0), 0);
  console.log(`written: ${n(s.packs)} pack entries, ${n(s.embedded)} embedded items`);
}
